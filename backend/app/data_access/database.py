@contextmanager
def database() -> Iterator[Any]:
    if using_postgres():
        if psycopg is None:
            raise RuntimeError("DATABASE_URL is set but psycopg is unavailable. Run `uv sync` in backend.")
        global IntegrityError
        IntegrityError = psycopg.IntegrityError
        raw_connection = psycopg.connect(settings.database_url, autocommit=False)
        connection = _PostgresConnection(raw_connection)
        try:
            yield connection
            connection.commit()
        except Exception:
            raw_connection.rollback()
            raise
        finally:
            connection.close()
        return
    connection = sqlite3.connect(_sqlite_path())
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    try:
        yield connection
        connection.commit()
    finally:
        connection.close()

