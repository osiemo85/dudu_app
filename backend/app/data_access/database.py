def _database_kind() -> str:
    url = settings.database_url.strip()
    if url.startswith(("postgres://", "postgresql://")):
        return "postgres"
    if url.startswith("sqlite:///"):
        return "sqlite"
    if not url:
        raise RuntimeError("DATABASE_URL is required. Set it to your Supabase/PostgreSQL URL or an explicit sqlite:/// URL.")
    raise RuntimeError("Unsupported DATABASE_URL scheme. Use postgresql://, postgres://, or sqlite:///.")


def using_postgres() -> bool:
    return _database_kind() == "postgres"


def _sqlite_path() -> str:
    """Return the path from an explicitly supplied sqlite:/// DATABASE_URL."""
    url = settings.database_url.strip()
    if _database_kind() != "sqlite":
        raise RuntimeError("A sqlite:/// DATABASE_URL is required for SQLite.")
    return unquote(url.removeprefix("sqlite:///"))


def _split_sql(script: str) -> list[str]:
    """Split fixture SQL without breaking semicolons inside quoted text."""
    statements: list[str] = []
    current: list[str] = []
    quote: str | None = None
    index = 0
    while index < len(script):
        character = script[index]
        following = script[index + 1] if index + 1 < len(script) else ""
        current.append(character)
        if quote:
            if character == quote:
                if following == quote:
                    current.append(following)
                    index += 1
                else:
                    quote = None
        elif character in {"'", '"'}:
            quote = character
        elif character == ";":
            statement = "".join(current[:-1]).strip()
            if statement:
                statements.append(statement)
            current = []
        index += 1
    statement = "".join(current).strip()
    if statement:
        statements.append(statement)
    return statements


def _postgres_script(script: str) -> list[str]:
    """Translate the small SQLite-only fixture dialect used by this demo."""
    script = re.sub(r"(?mi)^\s*PRAGMA[^;]*;\s*", "", script)
    script = re.sub(r"\bid\s+INTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script, flags=re.I)
    script = re.sub(r"\s+COLLATE\s+NOCASE", "", script, flags=re.I)
    statements = []
    for statement in _split_sql(script):
        idempotent = bool(re.search(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", statement, re.I))
        statement = re.sub(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", statement, flags=re.I)
        if idempotent:
            statement += " ON CONFLICT DO NOTHING"
        statements.append(statement)
    return statements


class _PostgresCursor:
    def __init__(self, cursor: Any, lastrowid: int | None = None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()


class _PostgresConnection:
    """Compatibility wrapper for existing repositories' SQLite-style calls."""
    def __init__(self, connection: Any):
        self._connection = connection

    def execute(self, query: str, parameters: tuple[Any, ...] = ()) -> _PostgresCursor:
        cursor = self._connection.cursor(row_factory=dict_row)
        cursor.execute(query.replace("?", "%s"), parameters)
        lastrowid = None
        if re.match(r"(?is)^\s*INSERT\b", query):
            identity_cursor = self._connection.cursor(row_factory=dict_row)
            identity_cursor.execute("SELECT LASTVAL() AS id")
            identity = identity_cursor.fetchone()
            lastrowid = int(identity["id"]) if identity else None
        return _PostgresCursor(cursor, lastrowid)

    def commit(self) -> None:
        self._connection.commit()

    def close(self) -> None:
        self._connection.close()


