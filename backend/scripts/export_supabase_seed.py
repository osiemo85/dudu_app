"""Print the manual PostgreSQL/Supabase schema and simulated fixture seed.

Run from ``backend`` and redirect the output to a file, then execute that file
in Supabase Dashboard -> SQL Editor. This script is deliberately not called by
the API, so serverless deployments never mutate the database at startup.
"""
import sys
from pathlib import Path

# Direct script execution places ``scripts/`` rather than ``backend/`` on
# sys.path. Add the backend root before importing application modules.
BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

from app.core.config import PROJECT_DIR
from app.data_access.database import _postgres_script


DATA_DIR = PROJECT_DIR / "data"


def emit(statement: str) -> None:
    print(statement.rstrip(";"))
    print(";")


def emit_file(name: str, *, ensure_planting_source: bool = False) -> None:
    for statement in _postgres_script((DATA_DIR / name).read_text(encoding="utf-8")):
        if ensure_planting_source and "INSERT INTO CROPS" in statement.upper():
            emit("""INSERT INTO sources (name, source_date, geographic_scope, evidence_status, limitations)
VALUES ('Shamba Guide demo planting calendar', '2025-01-15', 'Selected demonstration counties', 'simulated',
'Illustrative planning windows only; verify rainfall onset, soil condition, and current county advice before planting.')
ON CONFLICT(name, source_date, geographic_scope) DO NOTHING""")
        emit(statement)


def main() -> None:
    print("-- Generated manual Supabase schema and simulated demo fixtures.")
    print("-- Review before running. It creates/updates tables but does not delete data.\n")
    emit_file("seed.sql", ensure_planting_source=True)
    emit("""ALTER TABLE outbreaks ADD COLUMN IF NOT EXISTS latitude REAL, ADD COLUMN IF NOT EXISTS longitude REAL,
ADD COLUMN IF NOT EXISTS image_path TEXT, ADD COLUMN IF NOT EXISTS expert_approval TEXT NOT NULL DEFAULT 'not_required',
ADD COLUMN IF NOT EXISTS expert_review_note TEXT, ADD COLUMN IF NOT EXISTS llm_identified INTEGER NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS created_at TEXT, ADD COLUMN IF NOT EXISTS image_description TEXT, ADD COLUMN IF NOT EXISTS user_symptoms TEXT""")
    emit("""ALTER TABLE crops ADD COLUMN IF NOT EXISTS category TEXT, ADD COLUMN IF NOT EXISTS description TEXT,
ADD COLUMN IF NOT EXISTS rain_needed_months INTEGER, ADD COLUMN IF NOT EXISTS rain_needs_notes TEXT,
ADD COLUMN IF NOT EXISTS rain_needs_source_id BIGINT REFERENCES sources(id)""")
    emit("ALTER TABLE seasons ADD COLUMN IF NOT EXISTS name TEXT, ADD COLUMN IF NOT EXISTS description TEXT")
    emit("ALTER TABLE weather_forecasts ADD COLUMN IF NOT EXISTS area TEXT, ADD COLUMN IF NOT EXISTS rainy_months INTEGER")
    emit("UPDATE seasons SET name=label, description=basis WHERE name IS NULL OR description IS NULL")
    emit("UPDATE crops SET description=summary WHERE description IS NULL")
    emit("UPDATE crops SET category=CASE name WHEN 'Maize' THEN 'Cereal' WHEN 'Sorghum' THEN 'Cereal' WHEN 'Bean' THEN 'Legume' WHEN 'Potato' THEN 'Root' END WHERE category IS NULL")
    emit("""UPDATE crops SET rain_needed_months=CASE name WHEN 'Maize' THEN 4 WHEN 'Bean' THEN 3 WHEN 'Potato' THEN 3 WHEN 'Sorghum' THEN 2 END,
rain_needs_notes='Fictional duration for testing; not locally validated.' WHERE rain_needed_months IS NULL""")
    emit_file("planting_tables.sql")
    emit("""ALTER TABLE management_plans ADD COLUMN IF NOT EXISTS source_id BIGINT REFERENCES sources(id),
ADD COLUMN IF NOT EXISTS rain_needed_months INTEGER, ADD COLUMN IF NOT EXISTS rain_requirement_notes TEXT,
ADD COLUMN IF NOT EXISTS weeding_count INTEGER, ADD COLUMN IF NOT EXISTS fertility_notes TEXT""")
    emit("""INSERT INTO sources(name, source_date, geographic_scope, evidence_status, limitations)
VALUES ('Planting management test fixtures', '2025-01-15', 'Selected demonstration areas', 'simulated',
'Fictional management stages for testing, not locally validated agronomic advice.')
ON CONFLICT(name, source_date, geographic_scope) DO NOTHING""")
    emit("""UPDATE management_plans SET source_id=(SELECT id FROM sources WHERE name='Planting management test fixtures'
AND source_date='2025-01-15' AND geographic_scope='Selected demonstration areas')
WHERE source_id IS NULL AND (title LIKE 'Demo plan: %' OR title='Demo management plan')""")
    emit("""ALTER TABLE management_stages ADD COLUMN IF NOT EXISTS start_day_after_planting INTEGER,
ADD COLUMN IF NOT EXISTS end_day_after_planting INTEGER, ADD COLUMN IF NOT EXISTS timing_notes TEXT,
ADD COLUMN IF NOT EXISTS activity_type TEXT, ADD COLUMN IF NOT EXISTS weeding_round INTEGER""")
    emit("""CREATE TABLE IF NOT EXISTS stage_treatments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
management_stage_id BIGINT NOT NULL REFERENCES management_stages(id), treatment_type TEXT NOT NULL CHECK(treatment_type IN ('non_chemical','pesticide')),
name TEXT NOT NULL, timing_notes TEXT, guidance TEXT, source_id BIGINT REFERENCES sources(id), UNIQUE(management_stage_id,treatment_type,name))""")
    emit_file("management_enrichment.sql")
    emit_file("management_input_examples.sql")
    emit_file("user_plans.sql")
    emit("""DO $$ DECLARE item record; BEGIN FOR item IN SELECT table_name FROM information_schema.columns
WHERE table_schema='public' AND column_name='id' LOOP EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE((SELECT MAX(id) FROM %I),1), true)', item.table_name, 'id', item.table_name); END LOOP; END $$""")


if __name__ == "__main__":
    main()
